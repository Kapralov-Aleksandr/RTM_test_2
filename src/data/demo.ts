// ---------- Тест-кейсы ПМИ (для поиска «сирот») ----------
export function buildPmiRegistry(matrix: Requirement[]): PmiTest[] {
  const linked: PmiTest[] = matrix
    .filter((r) => r.testCase)
    .map((r) => ({
      code: r.testCase,
      title: `Проверка: ${r.text.charAt(0).toLowerCase()}${r.text.slice(1)}`,
      req: r.id,
    }));
  // «Сироты»: тесты без привязки к требованиям матрицы
  const orphans: PmiTest[] = [
    { code: 'TC-119', title: 'Проверка пагинации в реестре заявок', req: '' },
    { code: 'TC-122', title: 'Импорт расписания из CSV (вырезано из объёма)', req: 'REQ-099' },
    { code: 'TC-124', title: 'Нагрузочное тестирование личного кабинета', req: '' },
  ];
  return [...linked, ...orphans];
}

